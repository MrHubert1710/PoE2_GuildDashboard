import { test, expect } from '@playwright/test'

test.use({ locale: 'en-US' })

test('checkbox multiselect filters both tables and survives URL, reload and back/forward', async ({ page }) => {
  await page.goto('/poe2guild/?lang=en&page=2')
  await expect(page.getByTestId('transaction-results')).toBeVisible()
  const picker = page.getByRole('group', { name: 'Stashes', exact: true })
  const main = picker.getByRole('checkbox', { name: 'Main', exact: true })
  const special = picker.getByRole('checkbox', { name: 'Special', exact: true })
  await special.check()
  await expect(page.locator('.result-count')).toContainText('page 2')
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
  await expect(page.locator('.result-count')).toHaveText('Results: 1 · page 1 of 1')
  await expect(page.getByTestId('quantity-stats')).toContainText('Events: 1 ·')
  expect(new URL(page.url()).searchParams.getAll('stash')).toEqual(['Special'])
  await main.check()
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
  await expect(page.locator('.result-count')).toContainText('Results: 60')
  await expect(page.getByTestId('quantity-stats')).toContainText('Events: 60 ·')
  expect(new URL(page.url()).searchParams.getAll('stash')).toEqual(['Main', 'Special'])
  await page.reload()
  await expect(main).toBeChecked()
  await expect(special).toBeChecked()
  await page.goBack()
  await expect(main).not.toBeChecked()
  await expect(special).toBeChecked()
  await expect(page.locator('.result-count')).toContainText('Results: 1')
  await page.goForward()
  await expect(main).toBeChecked()
  await expect(page.locator('.result-count')).toContainText('Results: 60')
  await picker.getByRole('button', { name: 'All stashes', exact: true }).click()
  await expect(main).not.toBeChecked()
  await expect(special).not.toBeChecked()
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
  expect(new URL(page.url()).searchParams.getAll('stash')).toEqual([])
  await expect(page.locator('.result-count')).toContainText('Results: 60')
})

test('single stash links remain compatible and keyboard selection fits mobile in PL/EN', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('/poe2guild/?lang=pl&stash=Special')
  const picker = page.getByRole('group', { name: 'Skrytki', exact: true })
  await expect(picker.getByRole('checkbox', { name: 'Special', exact: true })).toBeChecked()
  const main = picker.getByRole('checkbox', { name: 'Main', exact: true })
  await main.focus()
  await main.press('Space')
  await expect(main).toBeChecked()
  await expect(picker).toContainText('Wybrane: 2')
  await page.getByRole('button', { name: 'Zastosuj filtry', exact: true }).click()
  await expect(page.locator('.result-count')).toContainText('Wyniki: 60')
  await page.getByRole('combobox', { name: 'Język', exact: true }).selectOption('en')
  await expect(page.getByRole('group', { name: 'Stashes', exact: true })).toContainText('Selected: 2')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Stashes', exact: true }).getByRole('checkbox', { name: 'Main', exact: true })).not.toBeChecked()
  await expect(page.locator('.result-count')).toContainText('Results: 60')
})

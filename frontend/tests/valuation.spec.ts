import {test,expect} from './fixtures'
const root='/poe2guild/?lang=en'

test('valuation is historical only and obsolete pricing URLs are cleaned without changing quantities',async({page,request})=>{
 await page.goto(root+'&section=players&chart_pricing=latest')
 await expect(page).not.toHaveURL(/chart_pricing=/)
 await expect(page.getByRole('switch',{name:'Value mode',exact:true})).toBeChecked()
 await expect(page.getByLabel('Chart item',{exact:true})).toHaveCount(0)
 await expect(page.getByRole('switch',{name:'Current prices',exact:true})).toHaveCount(0)
 await expect(page.getByTestId('time-series-chart')).toBeVisible()
 await expect(page.getByTestId('valuation-status')).toContainText('Historical daily prices')
 const league=new URL(page.url()).searchParams.get('league'),endpoint=`/poe2guild/api/leagues/${league}`
 const quantities=await(await request.get(endpoint+'/quantities')).json()
 const historical=await(await request.get(endpoint+'/quantity-series?mode=value&view=players')).json()
 expect(historical.pricing.mode).toBe('historical')
 expect((await request.get(endpoint+'/quantity-series?mode=value&pricing=latest')).status()).toBe(400)
 expect((await request.get(endpoint+'/valuations?mode=latest')).status()).toBe(400)
 expect((await(await request.get(endpoint+'/prices')).json()).valuations).toEqual({historical:true})
 await page.reload();await expect(page).not.toHaveURL(/chart_pricing=/)
 await expect(page.getByRole('switch',{name:'Current prices',exact:true})).toHaveCount(0)
 expect((await(await request.get(endpoint+'/quantities')).json()).projection.id).toBe(quantities.projection.id)
 await page.getByRole('switch',{name:'Value mode',exact:true}).uncheck()
 await expect(page.getByLabel('Chart item',{exact:true})).toBeVisible()
 await expect(page.getByTestId('valuation-report')).toHaveCount(0)
})

test('missing prices remain explicit and source provenance is visible in system settings',async({page})=>{
 await page.goto(root)
 await expect(page.getByTestId('valuation-report')).toContainText('Items without a price')
 await expect(page.getByTestId('valuation-report')).toContainText('No dated price observed')
 await page.getByRole('link',{name:'System settings',exact:true}).click()
 const sources=page.getByTestId('price-sources')
 await expect(sources).toContainText('Price sources')
 await expect(sources).toContainText('Price snapshots (2)')
 await sources.getByText('Price snapshots (2)',{exact:true}).click()
 await expect(sources).toContainText('Observed price')
 await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('pl')
 await expect(sources).toContainText('Źródła cen')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

test('stash value follows held inventory and price changes independently of player cash flows',async({page,request})=>{
 await page.goto(root+'&section=stashes')
 const report=page.getByTestId('valuation-report')
 await expect(report.getByRole('columnheader',{name:'Opening value',exact:true})).toBeVisible()
 await expect(report.getByRole('columnheader',{name:'Inventory value',exact:true})).toBeVisible()
 await expect(report.getByRole('columnheader',{name:'Added',exact:true})).toHaveCount(0)
 const league=new URL(page.url()).searchParams.get('league'),endpoint=`/poe2guild/api/leagues/${league}`
 const stock=await(await request.get(endpoint+'/quantity-series?mode=value&view=stashes')).json()
 const players=await(await request.get(endpoint+'/quantity-series?mode=value&view=players')).json()
 expect(stock.model).toBe('inventory')
 expect(stock.total_series.closing_balance).not.toBe(players.total_series.closing_balance)
 expect(stock.series.every((series:any)=>series.points.every((point:any)=>point.balance>=0))).toBe(true)
 const filtered=await(await request.get(endpoint+'/valuations?view=stashes&account=Nobody')).json()
 const all=await(await request.get(endpoint+'/valuations?view=stashes')).json()
 expect(filtered.account_filter_ignored).toBe(true)
 expect(filtered.rows).toEqual(all.rows)
 await page.getByLabel('Player',{exact:true}).fill('Nobody')
 await page.getByRole('button',{name:'Apply filters',exact:true}).click()
 await expect(report).toContainText('The player filter is ignored for inventory valuation')
 await expect(page.getByTestId('time-series-chart')).toBeVisible()
})

import {test,expect} from './fixtures'

test('administrator can store a masked session while public clients cannot read connection settings',async({page,request,browser})=>{
 await page.goto('/poe2guild/?lang=en&section=configuration')
 const panel=page.getByTestId('ggg-connection')
 await expect(panel.getByRole('heading',{name:'GGG connection',exact:true})).toBeVisible()
 const secret=panel.getByLabel('SESSION_ID (POESESSID)',{exact:true})
 await expect(secret).toHaveAttribute('type','password')
 await panel.getByLabel('GUILD_ID',{exact:true}).fill('123')
 const value='browser-test-session-never-a-real-cookie-123'
 await secret.fill(value)
 await panel.getByRole('button',{name:'Save connection',exact:true}).click()
 await expect(panel).toContainText('Connection saved.')
 await expect(secret).toHaveValue('')
 await expect(secret).toHaveAttribute('placeholder','Session stored — leave blank to keep it')
 const response=await request.get('/poe2guild/api/ggg-connection')
 expect(await response.text()).not.toContain(value)
 const body=await response.json();expect(body.connection.session_configured).toBe(true);expect(body.connection.enabled).toBe(0)
 await expect(panel.getByRole('button',{name:/trade|login|cookie/i})).toHaveCount(0)
 await page.reload();await expect(secret).toHaveValue('')
 const anonymous=await browser.newContext()
 expect((await anonymous.request.get('/poe2guild/api/ggg-connection')).status()).toBe(401)
 expect((await anonymous.request.post('/poe2guild/api/league-catalog/leagues',{data:{name:'Unauthorized'}})).status()).toBe(401)
 await anonymous.close()
})

test('catalog discovery needs admin approval and monitoring/status changes are explicit',async({page,request})=>{
 await page.goto('/poe2guild/?lang=en&section=configuration')
 const panel=page.getByTestId('league-catalog')
 await expect(panel).toContainText('Discovery does not add leagues')
 const initial=(await(await request.get('/poe2guild/api/leagues')).json()).leagues
 expect(initial.some((league:any)=>league.name==='Catalog Test League')).toBe(false)
 const name=initial[0].name
 const snapshot=(await(await request.get('/poe2guild/api/league-catalog')).json()).leagues.find((league:any)=>league.id===initial[0].id)
 const monitor=panel.getByRole('checkbox',{name:`Monitor: ${name}`,exact:true})
 await monitor.uncheck()
 await panel.getByRole('combobox',{name:`In-game status: ${name}`,exact:true}).selectOption('active')
 await panel.getByRole('button',{name:`Save league: ${name}`,exact:true}).click()
 await expect(panel).toContainText('League configuration saved.')
 const changed=(await(await request.get('/poe2guild/api/leagues')).json()).leagues.find((league:any)=>league.id===initial[0].id)
 expect(changed.monitored).toBe(false);expect(changed.lifecycle).toBe('active');expect(changed.lifecycle_source).toBe('manual')
 const current=(await(await request.get('/poe2guild/api/league-catalog')).json()).leagues.find((league:any)=>league.id===initial[0].id)
 await request.put('/poe2guild/api/league-catalog/leagues/'+current.id,{data:{monitored:snapshot.monitored,archived:snapshot.archived,lifecycle_override:snapshot.lifecycle_override,version:current.version}})
 await panel.getByRole('button',{name:'Add league: Catalog Test League',exact:true}).click()
 await expect(panel).toContainText('League configuration saved.')
 await expect(panel.getByRole('button',{name:'Add league: Catalog Test League',exact:true})).toHaveCount(0)
 const leagues=(await(await request.get('/poe2guild/api/leagues')).json()).leagues
 expect(leagues).toHaveLength(initial.length+1)
 const added=leagues.find((league:any)=>league.name==='Catalog Test League')
 expect(added.lifecycle).toBe('unknown');expect(added.transactions).toBe(0)
 await page.getByRole('combobox',{name:'League',exact:true}).click()
 await page.getByRole('option').filter({hasText:'Catalog Test League'}).click()
 await expect(page.getByRole('combobox',{name:'League',exact:true})).toContainText('Catalog Test League')
})

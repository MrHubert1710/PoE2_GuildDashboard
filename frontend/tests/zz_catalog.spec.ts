import {test,expect} from './fixtures'

test('administrator can store a masked session while public clients cannot read connection settings',async({page,request,browser})=>{
 await page.goto('/poe2guild/?lang=en&section=configuration')
 const panel=page.getByTestId('ggg-connection')
 await expect(panel.getByRole('heading',{name:'GGG connection',exact:true})).toBeVisible()
 const secret=panel.getByLabel('SESSION_ID (POESESSID)',{exact:true})
 await expect(secret).toHaveAttribute('type','password')
 await panel.getByLabel('GUILD_ID',{exact:true}).fill('123')
 const value='browser-test-session-never-a-real-cookie-123'
 await secret.fill(value)
 await panel.getByRole('button',{name:'Save connection',exact:true}).click()
 await expect(panel).toContainText('Connection saved.')
 await expect(secret).toHaveValue('')
 await expect(secret).toHaveAttribute('placeholder','Session stored — leave blank to keep it')
 const response=await request.get('/poe2guild/api/ggg-connection')
 expect(await response.text()).not.toContain(value)
 const body=await response.json();expect(body.connection.session_configured).toBe(true);expect(body.connection.enabled).toBe(0)
 await expect(panel.getByRole('button',{name:/trade|login|cookie/i})).toHaveCount(0)
 await page.reload();await expect(secret).toHaveValue('')
 const anonymous=await browser.newContext()
 expect((await anonymous.request.get('/poe2guild/api/ggg-connection')).status()).toBe(401)
 expect((await anonymous.request.post('/poe2guild/api/league-catalog/leagues',{data:{name:'Unauthorized'}})).status()).toBe(401)
 await anonymous.close()
})

test('catalog discovery needs admin approval and monitoring/status changes are explicit',async({page,request})=>{
 await page.goto('/poe2guild/?lang=en&section=configuration')
 const panel=page.getByTestId('league-catalog')
 await expect(panel).toContainText('Discovery does not add leagues')
 await expect(panel.getByRole('columnheader',{name:'Local archive',exact:true})).toHaveCount(0)
 await expect(panel.getByRole('checkbox',{name:/Local archive:/})).toHaveCount(0)
 const initial=(await(await request.get('/poe2guild/api/leagues')).json()).leagues
 expect(initial.some((league:any)=>league.name==='Catalog Test League')).toBe(false)
 const name=initial[0].name
 const snapshot=(await(await request.get('/poe2guild/api/league-catalog')).json()).leagues.find((league:any)=>league.id===initial[0].id)
 await expect(panel.getByRole('checkbox',{name:`Monitor: ${name}`,exact:true})).toHaveCount(0)
 await panel.getByRole('combobox',{name:`In-game status: ${name}`,exact:true}).selectOption('active')
 await panel.getByRole('button',{name:`Save league: ${name}`,exact:true}).click()
 await expect(panel).toContainText('League configuration saved.')
 const changed=(await(await request.get('/poe2guild/api/leagues')).json()).leagues.find((league:any)=>league.id===initial[0].id)
 expect(changed.monitored).toBe(true);expect(changed.lifecycle).toBe('active');expect(changed.lifecycle_source).toBe('manual')
 const current=(await(await request.get('/poe2guild/api/league-catalog')).json()).leagues.find((league:any)=>league.id===initial[0].id)
 await request.put('/poe2guild/api/league-catalog/leagues/'+current.id,{data:{lifecycle_override:snapshot.lifecycle_override,version:current.version}})
 await panel.getByRole('button',{name:'Add league: Catalog Test League',exact:true}).click()
 await expect(panel).toContainText('League configuration saved.')
 await expect(panel.getByRole('button',{name:'Add league: Catalog Test League',exact:true})).toHaveCount(0)
 const leagues=(await(await request.get('/poe2guild/api/leagues')).json()).leagues
 expect(leagues).toHaveLength(initial.length+1)
 const added=leagues.find((league:any)=>league.name==='Catalog Test League')
 expect(added.lifecycle).toBe('active');expect(added.transactions).toBe(0)
 await page.getByRole('combobox',{name:'League',exact:true}).click()
 await page.getByRole('option').filter({hasText:'Catalog Test League'}).click()
 await expect(page.getByRole('combobox',{name:'League',exact:true})).toContainText('Catalog Test League')
})

test('league deletion requires warning confirmation, updates selection and can be cancelled',async({page,request,browser})=>{
 const added=await(await request.post('/poe2guild/api/league-catalog/leagues',{data:{name:'Delete Test League'}})).json()
 await page.goto('/poe2guild/?lang=en&section=configuration&league='+added.league_id)
 const panel=page.getByTestId('league-catalog'),button=panel.getByRole('button',{name:'Delete league: Delete Test League',exact:true})
 await button.click()
 const popup=page.getByRole('dialog',{name:'Permanently delete league?',exact:true})
 await expect(popup).toBeVisible();await expect(popup).toContainText('This cannot be undone.')
 await expect(popup).toContainText('Delete Test League')
 await popup.getByRole('button',{name:'Cancel',exact:true}).click()
 await expect(popup).not.toBeVisible();await expect(button).toBeVisible()
 const anonymous=await browser.newContext()
 expect((await anonymous.request.delete('/poe2guild/api/league-catalog/leagues/'+added.league_id,{data:{name:'Delete Test League',version:0}})).status()).toBe(401)
 await anonymous.close()
 await button.click();await popup.getByRole('button',{name:'Permanently delete',exact:true}).click()
 await expect(popup).not.toBeVisible();await expect(button).toHaveCount(0)
 await expect(page).not.toHaveURL(new RegExp('league='+added.league_id))
 const leagues=(await(await request.get('/poe2guild/api/leagues')).json()).leagues
 expect(leagues.some((league:any)=>league.id===added.league_id)).toBe(false)
 await page.reload();await expect(panel.getByRole('button',{name:'Delete league: Delete Test League',exact:true})).toHaveCount(0)
})

test('automatic catalog status defaults to archived for an absent league and admin can override then restore it',async({page,request})=>{
 const name='Absent status test',created=await(await request.post('/poe2guild/api/league-catalog/leagues',{data:{name}})).json()
 await page.goto('/poe2guild/?lang=en&section=configuration&league='+created.league_id)
 const panel=page.getByTestId('league-catalog'),status=panel.getByRole('combobox',{name:'In-game status: '+name,exact:true}),picker=page.getByRole('combobox',{name:'League',exact:true})
 await expect(status).toHaveValue('')
 await expect(picker).toContainText('Archived')
 const row=panel.getByRole('row').filter({hasText:name}).first()
 await expect(row).toContainText('poe.ninja catalog')
 await status.selectOption('active')
 await panel.getByRole('button',{name:'Save league: '+name,exact:true}).click()
 await expect(picker).toContainText('Active')
 await status.selectOption('')
 await panel.getByRole('button',{name:'Save league: '+name,exact:true}).click()
 await expect(picker).toContainText('Archived')
 const state=(await(await request.get('/poe2guild/api/league-catalog')).json()).leagues.find((league:any)=>league.id===created.league_id)
 expect(state.observed_source).toBe('poe.ninja');expect(state.lifecycle_override).toBe(null)
 expect((await request.delete('/poe2guild/api/league-catalog/leagues/'+created.league_id,{data:{name,version:state.version}})).status()).toBe(200)
})
